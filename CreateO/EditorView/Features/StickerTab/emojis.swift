// MARK: - Main View
struct emojis: View {
    @Binding var selectedEmoji: String?

    @State private var selectedCategoryIndex: Int = 0

    private let columns = [GridItem(.adaptive(minimum: 46, maximum: 60), spacing: 0)]

    var body: some View {
        VStack(spacing: 0) {

            // ── Emoji Grid ──────────────────────────────────────────────
            ScrollView {
                LazyVGrid(columns: columns, spacing: 4) {
                    ForEach(emojiCategories[selectedCategoryIndex].emojis, id: \.self) { emoji in
                        Button {
                            selectedEmoji = emoji
                        } label: {
                            Text(emoji)
                                .font(.system(size: 30))
                                .frame(width: 46, height: 46)
                                .contentShape(Rectangle())
                        }
                        .buttonStyle(.plain)
                    }
                }
                .padding(.horizontal, 6)
                .padding(.top, 8)
                .padding(.bottom, 4)
            }

            Divider()

            // ── Category Tab Bar (like keyboard) ────────────────────────
            ScrollView(.horizontal, showsIndicators: false) {
                HStack(spacing: 0) {
                    ForEach(emojiCategories.indices, id: \.self) { index in
                        Button {
                            selectedCategoryIndex = index
                        } label: {
                            VStack(spacing: 3) {
                                Image(systemName: emojiCategories[index].icon)
                                    .font(.system(size: 18,
                                                  weight: selectedCategoryIndex == index ? .semibold : .regular))
                                    .foregroundStyle(selectedCategoryIndex == index
                                                     ? Color.primary
                                                     : Color.secondary)
                                    .frame(height: 24)

                                Capsule()
                                    .fill(selectedCategoryIndex == index ? Color.primary : Color.clear)
                                    .frame(width: 20, height: 2)
                            }
                            .frame(width: 48, height: 44)
                            .contentShape(Rectangle())
                        }
                        .buttonStyle(.plain)
                        .animation(.easeInOut(duration: 0.15), value: selectedCategoryIndex)
                    }
                }
                .padding(.horizontal, 4)
            }
            .frame(height: 50)
            .background(.ultraThinMaterial)
        }
    }
}

